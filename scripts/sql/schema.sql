-- ============================================================================
-- DEVICE
--
-- A device is anything that publishes the protocol on its topics with its
-- credentials. The hardware behind it is interchangeable.
-- ============================================================================

CREATE TABLE IF NOT EXISTS device (
    -- Internal surrogate key. INTEGER, not UUID, deliberately: `measurement` is
    -- the largest table this service will own and its primary key leads on this
    -- column, so the width is paid once per row AND once per index entry. The
    -- worker has to load the device row for every message anyway (community,
    -- status, ceiling, capacity), so resolving public_id -> id costs nothing
    -- extra — and it makes plan §7.5's "write last_reject_reason only for a
    -- device row that actually loaded" structurally impossible to violate: you
    -- cannot name the integer without having loaded the row.
    id                     INTEGER      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- The protocol's `device_id`. This is what appears in the topic, what IS the
    -- MQTT username, and what the enrolment response returns. Generated by
    -- OptimCE at device creation and pinned as the broker client id, so it is
    -- externally visible and must never be reused.
    public_id              UUID         NOT NULL UNIQUE,

    id_community           INTEGER      NOT NULL,

    -- shared.const.DeviceType. Phase 1 enrols PRODUCTION only (plan deviation 6).
    type                   SMALLINT     NOT NULL,

    -- The meter this device reports for. A PLAIN COLUMN, never an FK: it lives
    -- in crm_db. Validated against the CRM at creation time, because nothing
    -- else ever will — a typo'd EAN otherwise produces a device that ingests
    -- happily and is attributed to nobody, discovered months later with real
    -- data already stored against it.
    --
    -- NEVER denormalise id_member here. Ownership is resolved per timestamp
    -- (plan deviation 3): meter_data is time-sliced and a meter can change
    -- holder mid-month. A cached owner is the meter-transfer privacy leak — the
    -- previous occupant's credential keeps publishing, attributed to them, about
    -- someone else's household.
    ean                    VARCHAR(64)  NOT NULL,

    name                   VARCHAR(128) NOT NULL,

    -- shared.const.DeviceStatus: 1 PENDING, 2 ACTIVE, 3 REVOKED.
    status                 SMALLINT     NOT NULL DEFAULT 1,

    -- protocol §3.4. A smart meter's P1 port sees only the exchange with the
    -- grid. On a PURE INJECTION site (nothing consumes behind the meter) the
    -- export IS the production. Otherwise production is invisible and
    -- production_wh must be null — and OptimCE's views must say "export", not
    -- "production". Fixed at creation because it is a property of the site.
    pure_injection         BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Snapshot of crm_db meter_data.total_generating_capacity, taken at device
    -- creation. NAMED WITH ITS UNIT ON PURPOSE (plan deviation 4): the CRM
    -- column is documented in all four locales as the maximum power in kVA that
    -- the installation can INJECT — the AC inverter/connection limit, not the DC
    -- panel peak. A PV array is routinely oversized against its inverter, so
    -- this is a CEILING to clip against, never a capacity to trust.
    -- NULL for a device whose meter declares none.
    capacity_kva           NUMERIC(12, 3),

    -- Per-interval energy ceiling, applied to import_wh + export_wh. NULL means
    -- use settings.INGEST_DEFAULT_MAX_WH_PER_INTERVAL.
    max_wh_per_interval    DOUBLE PRECISION,

    -- Read from EVERY status message, not only at enrolment (protocol §3.2), so
    -- that a field upgrade is visible. "Which devices are running the broken
    -- 0.3.0?" is a question that only gets asked at the worst possible moment.
    connector_name         VARCHAR(64),
    connector_version      VARCHAR(32),

    enrolled_at            TIMESTAMPTZ,
    revoked_at             TIMESTAMPTZ,

    created_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- One live device per meter per community. Partial, so a revoked device does not
-- block re-enrolling the same meter — which is the normal recovery path when a
-- password is lost (protocol §5.2: the password is shown once and is never
-- recoverable).
CREATE UNIQUE INDEX IF NOT EXISTS uq_device_community_ean_live
    ON device (id_community, ean)
    WHERE status <> 3;

CREATE INDEX IF NOT EXISTS ix_device_community ON device (id_community);

DROP TRIGGER IF EXISTS trg_device_updated_at ON device;
CREATE TRIGGER trg_device_updated_at BEFORE UPDATE ON device
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- ============================================================================
-- ENROLMENT TOKEN
--
-- Single use, 72 hours, hashed at rest. plan §8.3.
-- ============================================================================

CREATE TABLE IF NOT EXISTS enrollment_token (
    id             INTEGER      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_device      INTEGER      NOT NULL REFERENCES device (id) ON DELETE CASCADE,
    id_community   INTEGER      NOT NULL,

    -- SHA-256 of the Crockford base32 token. The token itself is 128 bits of
    -- CSPRNG output, so there is nothing for a KDF to slow down — and a bcrypt
    -- hash would ALSO break this index, forcing a scan over every live token on
    -- a request the gateway cuts at 3000 ms. "Compared in constant time" (plan
    -- §8.3) is satisfied by construction here: the comparison is an index probe,
    -- not a byte loop.
    token_hash     CHAR(64)     NOT NULL UNIQUE,

    expires_at     TIMESTAMPTZ  NOT NULL,

    -- THE CLAIM LEASE, and why there are two columns rather than one.
    --
    -- plan §8.2: create the broker client FIRST, commit SECOND. Of the two
    -- possible half-failures only one is recoverable — an orphan dynsec client
    -- with no device row is swept up harmlessly, but a committed device holding
    -- a secret that authenticates nothing, with its one-time token already
    -- consumed, is a site visit to a box with no keyboard.
    --
    -- So the token is CLAIMED for a few seconds before the broker call and only
    -- marked consumed after both sides are done. A 504 in between leaves a claim
    -- that simply expires, rather than burning a credential the member never
    -- received.
    claimed_until  TIMESTAMPTZ,
    consumed_at    TIMESTAMPTZ,

    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- At most one unconsumed token per device. Issuing a new one invalidates the old.
CREATE UNIQUE INDEX IF NOT EXISTS uq_enrollment_token_device_unconsumed
    ON enrollment_token (id_device)
    WHERE consumed_at IS NULL;


-- ============================================================================
-- MEASUREMENT — partitioned monthly on ts
--
-- The primary key (id_device, ts) CONTAINS the partition key, which is what
-- makes `ON CONFLICT (id_device, ts) DO UPDATE` legal on the partitioned parent
-- — and that upsert is the whole of protocol §4.3's idempotence. A connector
-- that is unsure whether a message arrived is supposed to re-send it.
-- ============================================================================

CREATE TABLE IF NOT EXISTS measurement (
    id_device      INTEGER          NOT NULL,
    -- END of the interval, always (protocol §3.1 rule 1).
    ts             TIMESTAMPTZ      NOT NULL,

    -- Denormalised so that with_community_scope() can filter this table without
    -- a join. The house helper hard-codes `model.id_community` behind a
    -- `type: ignore`, so a table that does not carry this exact column name
    -- cannot be scoped at all.
    id_community   INTEGER          NOT NULL,

    interval_s     INTEGER          NOT NULL,

    -- DOUBLE PRECISION, never REAL. SUM(real) returns real, so step 8's rollups
    -- would accumulate float32 error across thousands of values and every
    -- displayed total would be quietly slightly wrong — nothing errors, and it
    -- is unfixable without rewriting history.
    import_wh      DOUBLE PRECISION NOT NULL,
    export_wh      DOUBLE PRECISION NOT NULL,
    production_wh  DOUBLE PRECISION,

    received_at    TIMESTAMPTZ      NOT NULL DEFAULT NOW(),

    PRIMARY KEY (id_device, ts)
) PARTITION BY RANGE (ts);

-- A DEFAULT partition exists so that a row outside every declared range is
-- STORED rather than raising (plan §6.2 rule 2) — the difference between a late
-- message kept and a late message lost.
--
-- Its cost is that a stopped create-ahead job is invisible at write time. Two
-- things pay it back: api/health/routes.py reports this table's row count and
-- fails readiness above zero, and step 8's job must DRAIN the default before
-- attaching a partition over a range it already holds rows in — `ATTACH
-- PARTITION` fails otherwise, at 00:00 UTC on the first of a month,
-- platform-wide.
--
-- It also means plan §7.5's "on a partition miss, repair in a new session and
-- retry once" is UNREACHABLE by construction. The branch is kept in the worker
-- only as defence in case someone drops this table.
CREATE TABLE IF NOT EXISTS measurement_default PARTITION OF measurement DEFAULT;

-- Community-scoped reads over a time window (build step 6). Leads with
-- id_community because every scoped query filters on it first.
CREATE INDEX IF NOT EXISTS ix_measurement_community_ts
    ON measurement (id_community, ts);


-- ---- The partition registry and the create-ahead function ------------------
--
-- plan §6.2 requires that "the same helper is used by the schema and by the
-- scheduler". That is only LITERALLY true if the helper is SQL. A Python helper
-- emitting DDL, mirrored by static FOR VALUES literals here, is two helpers —
-- and they disagree the first time one is edited, surfacing months later as a
-- failed ATTACH.
--
-- domain/partitions.py mirrors the naming and bounds for tests and for step 8's
-- retention job; tests/test_partitions.py pins the two together by reading
-- pg_get_expr(relpartbound) back out.

CREATE TABLE IF NOT EXISTS live_partitioned_table (
    table_name  VARCHAR(63) PRIMARY KEY,
    added_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Step 8 adds 'rollup_device_hour' here AND to domain/partitions.py's
-- PARTITIONED_TABLES. A job that names only `measurement` lets the rollups
-- freeze about four months in while ingestion goes on looking perfectly healthy.
INSERT INTO live_partitioned_table (table_name) VALUES ('measurement')
ON CONFLICT DO NOTHING;

CREATE OR REPLACE FUNCTION live_ensure_monthly_partitions(
    months_ahead INTEGER DEFAULT 6,
    months_back  INTEGER DEFAULT 2
)
RETURNS INTEGER AS $$
DECLARE
  tbl          RECORD;
  offset_m     INTEGER;
  lower_bound  TIMESTAMPTZ;
  upper_bound  TIMESTAMPTZ;
  child        TEXT;
  created      INTEGER := 0;
BEGIN
  FOR tbl IN SELECT table_name FROM live_partitioned_table LOOP
    FOR offset_m IN -months_back..months_ahead LOOP
      -- Anchored to UTC EXPLICITLY. date_trunc() on a timestamptz truncates in
      -- the SESSION's timezone, and provision.sh sets none — so without the
      -- round trip through UTC a boundary would land at 23:00 or 01:00 of the
      -- previous day whenever the session happened to be Europe/Brussels, and
      -- every partition in the database would be an hour wide of the Python
      -- helper that names it.
      lower_bound := (date_trunc('month', (now() AT TIME ZONE 'UTC'))
                      + make_interval(months => offset_m)) AT TIME ZONE 'UTC';
      upper_bound := (date_trunc('month', (now() AT TIME ZONE 'UTC'))
                      + make_interval(months => offset_m + 1)) AT TIME ZONE 'UTC';
      child := format('%s_%s', tbl.table_name, to_char(lower_bound AT TIME ZONE 'UTC', 'YYYY_MM'));

      -- IF NOT EXISTS makes the whole function idempotent, which is what lets it
      -- be called both from this file and from a daily tick.
      EXECUTE format(
        'CREATE TABLE IF NOT EXISTS %I PARTITION OF %I FOR VALUES FROM (%L) TO (%L)',
        child, tbl.table_name, lower_bound, upper_bound
      );
      created := created + 1;
    END LOOP;
  END LOOP;
  RETURN created;
END;
$$ LANGUAGE plpgsql;

-- Provision the current month and six ahead. `schema.sql` creates its OWN
-- partitions (plan §6.2 rule 1) rather than leaving it to a running worker: a
-- test database provisioned from this file must be able to insert a row, and if
-- partitions arrived only from a worker, every test would be blocked on fixture
-- DDL executed inside a rolled-back transaction — which fails intermittently and
-- in test-order-dependent ways.
SELECT live_ensure_monthly_partitions(6, 2);


-- ============================================================================
-- DEVICE_LAST — one row per device, upserted
--
-- TWO CLOCKS, and they are not interchangeable.
--
--   ts          — the DEVICE's measurement clock. Guards the measurement
--                 columns: `WHERE ts < EXCLUDED.ts`, so a six-hour-old reading
--                 arriving in a backlog is not displayed as the current value
--                 with a fresh timestamp. That is the highest-visibility silent
--                 bug available here (plan §7.5).
--
--   status_at   — the SERVER's receipt clock. Guards the liveness and diagnostic
--                 columns. An LWT payload is composed at CONNECT time and sits
--                 on the broker until the device dies, so its `ts` is OLDER than
--                 every online status that followed it. Guarding `online` on the
--                 device clock makes the LWT lose the comparison and a crashed
--                 device shows online for ever — in a row that looks perfectly
--                 fresh. Receipt-time ordering also makes retained-status replay
--                 on resubscribe correct rather than harmful.
-- ============================================================================

CREATE TABLE IF NOT EXISTS device_last (
    id_device           INTEGER          PRIMARY KEY
                                         REFERENCES device (id) ON DELETE CASCADE,
    id_community        INTEGER          NOT NULL,

    -- Measurement clock.
    ts                  TIMESTAMPTZ,
    power_w             INTEGER,

    -- Server receipt clock.
    status_at           TIMESTAMPTZ,
    online              BOOLEAN,
    diag                VARCHAR(32),
    diag_since          TIMESTAMPTZ,

    -- Written ONLY for a device row that actually loaded. Writing it for an
    -- unknown device id would raise a foreign-key violation that aborts the
    -- whole ingest transaction — which is why device_unknown is message-scoped
    -- and never reaches here.
    last_reject_reason  VARCHAR(48),
    last_reject_at      TIMESTAMPTZ,

    -- Advanced by telemetry AND by status, so that "never seen" and "offline"
    -- are distinguishable inside the first quarter-hour after a connect.
    last_seen_at        TIMESTAMPTZ,

    updated_at          TIMESTAMPTZ      NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_device_last_community ON device_last (id_community);

DROP TRIGGER IF EXISTS trg_device_last_updated_at ON device_last;
CREATE TRIGGER trg_device_last_updated_at BEFORE UPDATE ON device_last
