--
-- Single source of truth for the LOCAL (owned) database. The CRM core tables
-- (community, meter, meter_data, member, address, …) live in a separate
-- database and are NOT declared here; this service only reads them, as
-- live_data_svc, constrained by postgres/provision/30-crm-grants.sql.
-- Cross-DB references (ean, id_community) are plain columns, NEVER foreign
-- keys.
--
-- Mirrors shared/models/local_models.py.
--
-- NO GRANT STATEMENTS. provision.sh applies this file under `SET ROLE
-- live_data_svc`, so it must be ownership-neutral. Access is granted in
-- postgres/provision/{10-databases,20-schema-owner,30-crm-grants}.sql.
--
-- NO psql META-COMMANDS (\i, \set, …) and no bind parameters. tests/conftest.py
-- feeds this whole file to asyncpg's simple-query protocol, not to psql.
--
-- RE-RUNNABLE. `CREATE TABLE IF NOT EXISTS` NEVER ADDS A COLUMN, so an added
-- column also needs an idempotent `ALTER TABLE … ADD COLUMN IF NOT EXISTS`
-- beside its block — otherwise re-applying this file silently does nothing and
-- it surfaces at runtime as an UndefinedColumnError.
--
-- APPLIED ONCE, IN PRACTICE. provision.sh applies a schema only when the target
-- database has no relation of relkind 'r' or 'p' in schema public. A
-- partitioned parent is relkind 'p', so an existing database is correctly
-- detected as non-empty — which also means THIS FILE IS NEVER RE-APPLIED to a
-- live database. Partition rotation therefore cannot live here; it is a runtime
-- job (build step 8). What this file does is provision the first six months and
-- leave behind the function that the job will call.
--
-- SCOPE: all eleven build steps. The ten tables from plan §6.1 that this header
-- once listed as "deliberately absent" — rollup_device_hour/_day,
-- rollup_community_hour/_day, rollup_dirty, device_owner_window,
-- forecast_production, device_forecast_method, consent and consent_event — ARE
-- IN THIS FILE. They were held back until steps 7/8 so that step 8's design
-- decisions could not be frozen into a step where nothing could test them, and
-- they arrived through scripts/sql/migrations/0001_*.sql.
--
-- This file and the migrations carry the SAME statements, for a fresh database
-- and for a live one respectively. tests/test_schema_migration_parity.py
-- provisions one of each and compares normalised catalog snapshots, which is
-- what keeps them equal. `consent` and `consent_event` are still INERT: phase 2.
-- ============================================================================

